
import 'package:drift/drift.dart';

import 'products_table.dart';

class StockMovements extends Table {
  // ============================================================
  // ID
  // ============================================================

  IntColumn get id => integer().autoIncrement()();

  // ============================================================
  // المنتج
  // ============================================================

  IntColumn get productId =>
      integer().references(Products, #id)();

  // ============================================================
  // نوع الحركة
  //
  // purchase       = شراء
  // sale           = بيع
  // sale_return    = مرتجع بيع
  // purchase_return = مرتجع شراء
  // adjustment     = تسوية / جرد
  // opening        = رصيد افتتاحي
  // ============================================================

  TextColumn get type =>
      text().withLength(min: 1, max: 50)();

  // ============================================================
  // الكمية
  //
  // موجب = إضافة للمخزون
  // سالب = خصم من المخزون
  // ============================================================

  RealColumn get quantity =>
      real().withDefault(const Constant(0))();

  // ============================================================
  // رصيد المخزون بعد الحركة
  // ============================================================

  RealColumn get balanceAfter =>
      real().withDefault(const Constant(0))();

  // ============================================================
  // مرجع العملية
  //
  // يمكن أن يكون رقم الفاتورة أو رقم عملية أخرى
  // ============================================================

  TextColumn get referenceNumber =>
      text().nullable()();

  // ============================================================
  // رقم العملية المرتبطة
  //
  // مثال:
  // Sale ID
  // Purchase ID
  // Return ID
  // ============================================================

  IntColumn get referenceId =>
      integer().nullable()();

  // ============================================================
  // ملاحظات
  // ============================================================

  TextColumn get notes =>
      text().nullable()();

  // ============================================================
  // تاريخ الحركة
  // ============================================================

  DateTimeColumn get createdAt =>
      dateTime().withDefault(currentDateAndTime)();
}
